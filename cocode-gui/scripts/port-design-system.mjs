/**
 * Ports the component layer of `.dev/guide/design-system.html` — the visual
 * authority — into `packages/ui/src/design-system.css`.
 *
 * The port is mechanical on purpose. Hand-copying is how the authority quietly
 * stops being authoritative; with a generator, a rule that exists in the HTML
 * either reaches the product or fails a check.
 *
 * Two regions are skipped because another file owns them: the token blocks
 * (`tokens.css`) and the element reset (`base.css`).
 *
 * Run with `--check` to verify the committed output matches the authority.
 */

import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const ROOT = new URL('..', import.meta.url)
const AUTHORITY = new URL('.dev/guide/design-system.html', ROOT)
const OUTPUT = new URL('packages/ui/src/design-system.css', ROOT)

const HEADER = `/**
 * The design system's component layer, taken from
 * \`.dev/guide/design-system.html\` — the visual authority (design system §7.1).
 *
 * GENERATED by \`scripts/port-design-system.mjs\`; do not edit. A visual change
 * starts in the HTML, then \`pnpm run port:design-system\` brings it here.
 *
 * Two regions of the authority's stylesheet are deliberately absent because
 * another file owns them: the token blocks live in \`tokens.css\`, and the
 * element reset lives in \`base.css\`.
 *
 * Everything sits in Tailwind's \`components\` layer so utilities still win,
 * which keeps layout glue at a call site from being outranked by a component rule.
 */

@layer components {
`

/** Extracts the authority's component rules, minus the regions other files own. */
function extractComponentCss(html) {
  const style = /<style>([\s\S]*?)<\/style>/.exec(html)
  if (style === null) throw new Error('design-system.html has no <style> block')

  const lines = style[1].split('\n')
  const out = []
  // The two owned regions are recognised by their opening selector and skipped
  // to their closing brace, so adding a rule to either cannot silently leak here.
  const ownedElsewhere = /^\s*(:root|\[data-theme="dark"\]\s*\{|\*\s*\{|html\s*\{|body\s*\{|button,\s*input,\s*textarea|button\s*\{|a\s*\{|code,\s*pre|:focus-visible)/
  let skipDepth = 0

  for (const line of lines) {
    if (skipDepth > 0) {
      skipDepth += (line.match(/\{/g) ?? []).length
      skipDepth -= (line.match(/\}/g) ?? []).length
      continue
    }
    if (ownedElsewhere.test(line)) {
      const opens = (line.match(/\{/g) ?? []).length
      const closes = (line.match(/\}/g) ?? []).length
      if (opens > closes) skipDepth = opens - closes
      continue
    }
    out.push(line.startsWith('      ') ? line.slice(6) : line)
  }

  return out.join('\n').replace(/\n{3,}/g, '\n\n').trim()
}

const html = await readFile(fileURLToPath(AUTHORITY), 'utf8')
const body = extractComponentCss(html)
const indented = body
  .split('\n')
  .map(line => (line.trim() === '' ? '' : `  ${line}`))
  .join('\n')
const generated = `${HEADER}${indented}\n}\n`

if (process.argv.includes('--check')) {
  const current = await readFile(fileURLToPath(OUTPUT), 'utf8').catch(() => '')
  if (current !== generated) {
    console.error('packages/ui/src/design-system.css is stale — run `pnpm run port:design-system`')
    process.exit(1)
  }
  console.log('check:design-system ok')
}
else {
  await writeFile(fileURLToPath(OUTPUT), generated)
  console.log('ported packages/ui/src/design-system.css')
}
